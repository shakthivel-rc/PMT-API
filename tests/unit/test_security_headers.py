"""Response headers, and the middleware order that decides who gets them.

Two separate things are pinned here.

**The headers themselves.** `nginx.conf` sets a full set for the origin that serves the
SPA. The API is a different service on a different port, reachable directly, and it set
none — "the reverse proxy does it" is only true of the origin the reverse proxy serves.

**The order.** `CORSMiddleware` used to be added first, which in Starlette means innermost,
which means a 401 generated by `JWTAuthMiddleware` above it never got an
`Access-Control-Allow-Origin`. Preflight worked, so it looked fine; what actually happened
in a browser was that an expired session produced an opaque network failure instead of a
readable 401, and the SPA could not tell "you are signed out" from "the server is down".
That is a regression with no visible symptom in any test that does not check for it, which
is exactly the kind worth a test.
"""
from dataclasses import replace

import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient

from core.config import get_settings
from core.middleware import SecurityHeadersMiddleware

pytestmark = pytest.mark.unit

ORIGIN = "http://localhost:3000"


def _app(**overrides) -> TestClient:
    settings = replace(get_settings(), **overrides) if overrides else get_settings()
    app = FastAPI()

    @app.get("/thing")
    def thing():
        return {"ok": True}

    @app.get("/docs")
    def docs():
        return {"swagger": True}

    app.add_middleware(SecurityHeadersMiddleware, settings=settings)
    return TestClient(app)


class TestSecurityHeaders:
    @pytest.mark.parametrize(
        "header,value",
        [
            ("X-Content-Type-Options", "nosniff"),
            ("X-Frame-Options", "DENY"),
            ("Referrer-Policy", "no-referrer"),
            ("Cross-Origin-Opener-Policy", "same-origin"),
        ],
    )
    def test_every_response_carries_them(self, header, value):
        assert _app().get("/thing").headers[header] == value

    def test_a_json_api_declares_it_needs_nothing(self):
        csp = _app().get("/thing").headers["Content-Security-Policy"]
        assert "default-src 'none'" in csp
        assert "frame-ancestors 'none'" in csp

    def test_swagger_is_exempt_from_the_json_policy(self):
        """`default-src 'none'` on Swagger UI is a blank page and a lesson in ignoring CSP."""
        assert "Content-Security-Policy" not in _app().get("/docs").headers

    def test_hsts_is_production_only(self):
        """Not correctness — a browser ignores HSTS over plain HTTP. It is 'do not pin a
        developer's localhost to HTTPS for a year', which is tedious to undo."""
        assert "Strict-Transport-Security" not in _app(environment="development").get(
            "/thing").headers
        assert "Strict-Transport-Security" in _app(environment="prod").get("/thing").headers


class TestMiddlewareOrder:
    """Against the real app, because the thing under test IS the wiring in main.py."""

    def test_an_unauthenticated_rejection_is_readable_by_the_browser(self, client):
        response = client.get("/api/v1/users", headers={"Origin": ORIGIN})
        assert response.status_code == 401
        assert response.headers.get("access-control-allow-origin") == ORIGIN, (
            "CORSMiddleware is inside the middleware that produced this 401, so a browser "
            "will report a CORS failure instead of an authentication failure."
        )

    def test_preflight_still_works(self, client):
        response = client.options(
            "/api/v1/users",
            headers={"Origin": ORIGIN, "Access-Control-Request-Method": "GET"},
        )
        assert response.status_code == 200
        assert response.headers.get("access-control-allow-origin") == ORIGIN

    def test_the_api_advertises_only_the_methods_it_serves(self, client):
        """No `*`. PATCH is the one method on the list that no route serves yet; it stays
        because the SPA's api client ships a generic `patch()` helper (see the comment on
        `allow_methods` in `main.py`)."""
        allowed = client.options(
            "/api/v1/users",
            headers={"Origin": ORIGIN, "Access-Control-Request-Method": "GET"},
        ).headers["access-control-allow-methods"]
        assert "*" not in allowed
        assert set(allowed.replace(" ", "").split(",")) == {
            "GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"
        }

    def test_the_correlation_id_is_readable_cross_origin(self, client):
        """`X-Request-ID` is set on every response and was invisible to the SPA without
        an `expose_headers` entry — a support workflow that quietly did not work."""
        response = client.get("/api/v1/health/live", headers={"Origin": ORIGIN})
        assert "X-Request-ID" in response.headers
        exposed = response.headers.get("access-control-expose-headers", "")
        assert "X-Request-ID" in exposed

    def test_the_real_app_sets_the_security_headers_too(self, client):
        headers = client.get("/api/v1/health/live").headers
        assert headers["X-Content-Type-Options"] == "nosniff"
        assert headers["X-Frame-Options"] == "DENY"
