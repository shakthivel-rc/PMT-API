"""SEC-5 and P-1: what `user_sessions` is allowed to contain, and what it is indexed on.

Everything asserted here is a property of the schema, of `hash_session_token`, or of the
constant that equalises login's two timing branches — none of it needs a database, so none
of it is here. The round trip that proves the whole thing works end to end (log in, read
the row, log out, watch the token stop authenticating) is in
`tests/integration/test_auth_enumeration.py`, which already has the login endpoint wired up.

The failure these guard against is unusual and worth naming: nothing in this area *raises*
when it breaks. A hash written with one definition and read with another matches no row, so
the whole service answers "Invalid session or token revoked" to every authenticated request
and no log line says why. A missing index does not fail at all — it just gets slower with
every session ever issued.
"""
import hashlib

import bcrypt
import pytest
from sqlalchemy import CHAR

from controllers.auth_controller import _DUMMY_PASSWORD_HASH, create_jwt_token
from models.user_session import UserSession, hash_session_token

pytestmark = pytest.mark.unit

TOKEN_COLUMN = UserSession.__table__.c.access_token_hash


def test_no_column_of_the_session_table_can_hold_a_raw_token():
    """Catches a raw `access_token` or `refresh_token` column coming back.

    They were both here, and `refresh_token` sat next to the hash of the same value for
    months without anyone noticing that the hash had not replaced it. A column re-added by
    an autogenerated revision, or by a merge that resurrected the old model, breaks nothing
    visible: everything keeps working, and the table quietly becomes a set of credentials
    again. The names are asserted as absent because that is the only symptom there is.
    """
    columns = {column.name for column in UserSession.__table__.columns}

    assert "access_token" not in columns, "the raw access token is back in the schema"
    assert "refresh_token" not in columns, "the raw refresh token is back in the schema"
    assert "access_token_hash" in columns
    assert "refresh_token_hash" in columns


def test_the_access_token_hash_column_is_indexed():
    """P-1. Catches the index being dropped, which nothing else would ever notice.

    This column is read on every authenticated request — the highest-frequency query in the
    service. Without the index the query still returns the right row, so every test in the
    suite still passes and the only symptom is that the login-protected half of the product
    gets linearly slower as `user_sessions` grows. That is precisely the shape of regression
    a test has to catch, because nobody is going to spot it in review.
    """
    indexed = [index for index in UserSession.__table__.indexes
               if [column.name for column in index.columns] == ["access_token_hash"]]

    assert indexed, "access_token_hash is not indexed; every request full-scans the table"


def test_the_hash_column_is_exactly_as_wide_as_a_digest():
    """Catches a column too narrow to hold what is written into it.

    MySQL truncates an over-long value into a `CHAR`/`VARCHAR` rather than refusing it under
    the default non-strict modes, and a truncated digest is a digest that matches nothing.
    The symptom would be that logging in appears to succeed and the very next request is
    401, for every user at once. 64 is not a round number chosen for comfort: it is the
    length of a hex SHA-256 digest, and the assertion below derives it rather than repeating
    it, so changing the hash function fails here instead of in production.
    """
    digest = hash_session_token("any-token-at-all")

    assert isinstance(TOKEN_COLUMN.type, CHAR)
    assert TOKEN_COLUMN.type.length == len(digest) == 64
    assert TOKEN_COLUMN.nullable is False, "a session row that cannot name its own token"


def test_hashing_a_token_is_sha256_of_its_utf8_bytes():
    """Pins the exact definition the column's contents depend on.

    Not a tautology, because there is more than one way to be wrong here and none of them
    raises: hashing the `repr`, hashing latin-1 bytes, returning `digest()` instead of
    `hexdigest()`, upper-casing the hex. Each writes a value that is stable, plausible and
    matches nothing written by the previous definition — which logs out every session in the
    deployment at the moment the change is deployed, with no error anywhere.
    """
    token = "eyJhbGciOiJIUzI1NiJ9.payload.signature"
    expected = hashlib.sha256(token.encode("utf-8")).hexdigest()

    assert hash_session_token(token) == expected
    assert hash_session_token(token) == hash_session_token(token)
    assert set(hash_session_token(token)) <= set("0123456789abcdef")


def test_create_jwt_token_returns_the_hashes_of_the_tokens_it_returns():
    """The two halves of a session row are minted together, so they cannot disagree.

    `login_controller` and `refresh_token_controller` both write `access_token_hash` from
    this dict and hand the caller the token from the same dict. If the two ever came from
    different places — a re-mint, a stale variable, a copy-paste between the access and
    refresh keys — the caller would leave holding a token that no row matches, and would be
    signed out on its first request while the login response said "success".
    """
    minted = create_jwt_token("user-under-test")

    assert minted["access_token_hash"] == hash_session_token(minted["access_token"])
    assert minted["refresh_token_hash"] == hash_session_token(minted["refresh_token"])
    assert minted["access_token"] != minted["refresh_token"]


def test_the_dummy_password_hash_costs_what_a_real_one_costs():
    """SEC-6's timing half is a placebo unless this hash is a real bcrypt hash of real cost.

    `login_controller` compares an unknown account's submitted password against
    `_DUMMY_PASSWORD_HASH` purely to spend the time a known account spends in `checkpw`.
    Two ways that silently stops working, both of which leave the code looking correct:
    the constant stops being a valid bcrypt string, in which case `verify_password` catches
    the `ValueError` and returns False in microseconds; or its work factor drifts below the
    one `hash_password` writes today, in which case the miss branch is measurably faster
    than the hit branch again and the enumeration oracle is back.

    `bcrypt.gensalt()` is compared against rather than a freshly hashed password because it
    is where `hash_password` gets its cost from, and unlike hashing it is free.
    """
    assert _DUMMY_PASSWORD_HASH.startswith("$2b$"), "not a bcrypt modular-crypt string"

    dummy_rounds = _DUMMY_PASSWORD_HASH.split("$")[2]
    current_rounds = bcrypt.gensalt().decode("ascii").split("$")[2]

    assert dummy_rounds == current_rounds, (
        f"the dummy hash costs {dummy_rounds} rounds and a real one now costs "
        f"{current_rounds}; the unknown-account branch is the faster one again"
    )
